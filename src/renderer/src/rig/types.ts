/** 部件面板里的一行（由 MeshPart 派生，供 React 使用） */
export interface PartListItem {
  id: string
  name: string
  meshName: string
  vertices: number
  faces: number
  visible: boolean
  selected: boolean
  /** 所属「组合」的 id（一个部件最多属于一个组） */
  groupId: string | null
  /** 网格局部空间的高度区间，帮助识别部件位置 */
  minY: number
  maxY: number
  /** 按骨骼区域拆分时的主导骨骼（最多两根） */
  bones?: string[]
}

/** 部件组合：把若干部件归成一组，整组显隐 / 整组导出 */
export interface PartGroup {
  id: string
  name: string
  partIds: string[]
}

