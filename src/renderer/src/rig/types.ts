/** One bone of the imported skeleton, expressed in world space at rest. */
export interface BoneInfo {
  name: string
  index: number
  parentIndex: number
  depth: number
  /** world-space head at rest */
  head: THREE.Vector3
  /** world-space tail at rest (child head, or extrapolated for leaves) */
  tail: THREE.Vector3
  length: number
  children: number[]
  role: BoneRole | null
}

export interface LocalTransform {
  position: THREE.Vector3
  quaternion: THREE.Quaternion
  scale: THREE.Vector3
}

/** A loaded, analysable skin + skeleton pair. */
export interface RigInfo {
  scene: THREE.Object3D
  skeleton: THREE.Skeleton
  bones: THREE.Bone[]
  boneInfo: BoneInfo[]
  meshes: THREE.SkinnedMesh[]
  /** world height of the bind pose */
  height: number
  /** world bounding box centre */
  center: THREE.Vector3
  up: THREE.Vector3
  /** horizontal facing direction, refined by semantics */
  forward: THREE.Vector3
  right: THREE.Vector3
  /** per bone, local transform at bind time */
  restLocal: LocalTransform[]
  /** per bone, world rotation at bind time */
  restWorldQuat: THREE.Quaternion[]
  boneIndexByName: Map<string, number>
  /** number of verts with at least one bone influence, for diagnostics */
  skinnedVertexCount: number
}

export interface SemanticRig {
  /** bone name -> single anatomical role */
  bones: Record<string, BoneRole>
  /** bottom (hips) -> top (chest) spine chain excluding neck / head */
  spineChain: string[]
  /** every tail bone, base -> tip */
  tailChain: string[]
  /** hair / back attachments, base -> tip */
  hairChains: string[][]
  /** five finger chains per hand, base -> tip */
  fingerChains: { L: string[][]; R: string[][] }
  /** ear / antenna chains, base -> tip */
  earChains: { L: string[]; R: string[] }
  /** follower bone -> driver bone, for duplicate / mirrored chains (Tripo SmartRig) */
  followMap: Record<string, string>
  warnings: string[]
  autoGenerated: boolean
}

export interface PoseTrack {
  bone: string
  /** seconds, strictly increasing, first value should be 0 */
  times: number[]
  /** local quaternion (absolute, relative to parent bone) at each time */
  quats: THREE.Quaternion[]
  /**
   * 可选：每帧的局部位移（相对父骨骼）。缺省表示该骨骼只做旋转、位置保持绑定姿态。
   * 由「逐帧精修」写入手工平移关键帧；导出时会变成 glTF 的 translation 轨道。
   */
  points?: THREE.Vector3[]
}

export interface PoseClip {
  id: string
  name: string
  kind: string
  duration: number
  fps: number
  tracks: PoseTrack[]
  /** optional root translation offset, sampled per frame */
  rootTrack?: { times: number[]; values: THREE.Vector3[] }
  /** how rootTrack values are expressed; actions generate 'world', imported clips are 'local' */
  rootSpace?: 'world' | 'local'
  loop: boolean
  builtin: boolean
  /** 手工逐帧精修过的动作：改变绑定姿态时不再自动重建，避免覆盖手工关键帧 */
  edited?: boolean
  /** 手工打过关键帧的帧号（升序），用于时间轴标记 */
  editedFrames?: number[]
}

export interface SampledPose {
  quats: Map<string, THREE.Quaternion>
  rootOffset: THREE.Vector3
  /** 带位移轨道的骨骼在 t 时刻的局部位移；没有位移轨道的骨骼不出现 */
  points?: Map<string, THREE.Vector3>
}

